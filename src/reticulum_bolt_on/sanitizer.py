"""Privileged, one-way sanitization boundary for root-owned RNS configs."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import stat
import time
from pathlib import Path
from typing import Any

from .parsers import parse_config_interfaces

SAFE_SHARED_FIELDS = ("instance_name", "shared_instance_type", "shared_instance_port", "instance_control_port")


class UnsafeObserverConfiguration(ValueError):
    pass


def _boolean(value: Any, default: bool = False) -> bool:
    if value is None:
        return default
    return str(value).strip().lower() in {"yes", "true", "1", "on"}


def _atomic_text(path: Path, content: str, mode: int = 0o644) -> None:
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    temporary.write_text(content, encoding="utf-8")
    os.chmod(temporary, mode)
    os.replace(temporary, path)


def _safe_shared_settings(settings: dict[str, str]) -> dict[str, str]:
    if settings.get("rpc_key", "").strip():
        raise UnsafeObserverConfiguration("A custom rpc_key is configured; Observer Mode will not copy shared-instance credentials.")
    if "share_instance" in settings and not _boolean(settings["share_instance"]):
        raise UnsafeObserverConfiguration("The selected Reticulum configuration does not enable a shared instance.")
    output: dict[str, str] = {"share_instance": "Yes", "enable_transport": "No"}
    for key in SAFE_SHARED_FIELDS:
        value = settings.get(key, "").strip()
        if not value:
            continue
        if any(character in value for character in "\r\n") or len(value) > 255:
            raise UnsafeObserverConfiguration(f"Invalid {key} value")
        if key == "shared_instance_type":
            if value.lower() not in {"tcp", "unix"}:
                raise UnsafeObserverConfiguration("Unsupported shared_instance_type")
            value = value.lower()
        if key.endswith("_port"):
            try:
                port = int(value)
            except ValueError as error:
                raise UnsafeObserverConfiguration(f"Invalid {key}") from error
            if not 1 <= port <= 65535:
                raise UnsafeObserverConfiguration(f"Invalid {key}")
            value = str(port)
        output[key] = value
    return output


def _minimal_config(settings: dict[str, str]) -> str:
    safe = _safe_shared_settings(settings)
    lines = ["# Generated by Reticulum Bolt-On Admin. Contains no interface credentials.", "[reticulum]"]
    lines.extend(f"  {key} = {value}" for key, value in safe.items())
    return "\n".join(lines) + "\n"


def sanitize_config(source: Path, output_dir: Path, *, source_display_path: str | None = None,
                    storage_display_path: str | None = None, deployment_type: str = "docker") -> dict[str, Any]:
    source = source.resolve()
    raw = source.read_bytes()
    text = raw.decode("utf-8", errors="replace")
    sections, interfaces = parse_config_interfaces(text)
    reticulum = sections.get("reticulum", {})
    minimal = _minimal_config(reticulum)
    output_dir.mkdir(parents=True, exist_ok=True)
    os.chmod(output_dir, 0o755)
    rns_dir = output_dir / "rns"
    for directory in (rns_dir, rns_dir / "storage", rns_dir / "storage/cache", rns_dir / "storage/cache/announces",
                      rns_dir / "storage/resources", rns_dir / "storage/identities", rns_dir / "storage/blackhole",
                      rns_dir / "interfaces"):
        directory.mkdir(parents=True, exist_ok=True)
        os.chmod(directory, 0o755)
    display_config = source_display_path or str(source)
    display_storage = storage_display_path or str(Path(display_config).parent / "storage")
    source_stat = source.stat()
    snapshot = {
        "schema_version": 1,
        "refreshed_at": int(time.time()),
        "source": {
            "config_path": display_config,
            "storage_path": display_storage,
            "sha256": hashlib.sha256(raw).hexdigest(),
            "mode": stat.S_IMODE(source_stat.st_mode),
        },
        "deployment_type": deployment_type,
        "transport_enabled": _boolean(reticulum.get("enable_transport")),
        "interfaces": interfaces,
        "storage_readable_at_refresh": (source.parent / "storage").is_dir(),
    }
    _atomic_text(rns_dir / "config", minimal)
    _atomic_text(output_dir / "config-view.json", json.dumps(snapshot, indent=2, sort_keys=True) + "\n")
    _atomic_text(output_dir / "refresh-status.json", json.dumps({
        "ok": True, "checked_at": int(time.time()), "source_sha256": snapshot["source"]["sha256"], "error": None,
    }, sort_keys=True) + "\n")
    return snapshot


def _write_failure(output_dir: Path, source: Path, error: Exception) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    digest = None
    try:
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
    except OSError:
        pass
    _atomic_text(output_dir / "refresh-status.json", json.dumps({
        "ok": False, "checked_at": int(time.time()), "source_sha256": digest,
        "error": f"Sanitized config refresh failed: {error}",
    }, sort_keys=True) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="Create credential-free observer inputs from an existing Reticulum config")
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--source-display-path")
    parser.add_argument("--storage-display-path")
    parser.add_argument("--deployment-type", default="docker")
    parser.add_argument("--watch-seconds", type=int, default=0)
    args = parser.parse_args()
    while True:
        try:
            sanitize_config(args.source, args.output_dir, source_display_path=args.source_display_path,
                            storage_display_path=args.storage_display_path, deployment_type=args.deployment_type)
        except Exception as error:
            _write_failure(args.output_dir, args.source, error)
            if not args.watch_seconds:
                raise SystemExit(str(error))
        if not args.watch_seconds:
            return
        time.sleep(max(5, args.watch_seconds))


if __name__ == "__main__":
    main()
